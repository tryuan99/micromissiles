// Beamformer configuration struct.
typedef struct {
  // SPI I/O configuration.
  spi_io_config_t spi_io_config;

  // TX load GPIO.
  uint8_t gpio_tx_load;

  // Transmit/receive GPIO.
  uint8_t gpio_transmit_receive;
} beamformer_config_t;

// Beamformer TX channel configuration struct.
typedef struct {
  // If true, the channel is enabled.
  bool enabled;

  // Attenuator setting.
  beamformer_attenuator_e attenuator;

  // TX VGA gain.
  uint8_t vga_gain;

  // Phase.
  beamformer_phase_e phase;
} beamformer_tx_channel_config_t;

typedef struct {
  // TX channel configurations.
  beamformer_tx_channel_config_t channel_configs[BEAMFORMER_NUM_CHANNELS];
} beamformer_tx_config_t;

// Initialize the beamformer chip.
void beamformer_init(const beamformer_config_t* config);

// Reset the beamformer.
void beamformer_reset(void);

// Configure the beamformer TX channels.
void beamformer_configure_tx(const beamformer_tx_config_t* config);

// Pulse the TX load pin to load the new TX configuration.
void beamformer_load_tx(void);

